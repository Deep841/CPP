//Implement Control Characters
#include <iostream>
using namespace std;

int main() {
    cout << "Line one\nLine two using \\n" << endl;
    cout << "Tab\tSpace using \\t" << endl;
    cout << "Alarm Sound\a" << endl; // May beep depending on system!
    cout << "Carriage return\rOverwrites line using \\r" << endl;
    return 0;
}
